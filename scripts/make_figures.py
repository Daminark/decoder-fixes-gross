"""Regenerate the cached experiment results that the documentation renders.

One function per result.
Each run writes the result data and, next to it, a JSON record of the configuration that produced it.
Notebooks under docs/ load these results and render the figures during the docs build.
A figure the README embeds is written here too, as a derived artifact regenerated by this command.
"""

import dataclasses
import json
import logging
import subprocess
from dataclasses import dataclass
from pathlib import Path

OUT = Path("results")
logger = logging.getLogger(__name__)


@dataclass(frozen=True)
class FigureConfig:
    """Parameters of one artifact, serialized next to it."""

    name: str
    seed: int
    commit: str


def commit_hash() -> str:
    """Return the short hash of HEAD, or "unknown" outside a git checkout."""
    result = subprocess.run(
        ["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True, check=False
    )
    return result.stdout.strip() or "unknown"


def write_record(config: FigureConfig) -> None:
    """Write the configuration record for one result."""
    path = OUT / f"{config.name}.json"
    path.write_text(json.dumps(dataclasses.asdict(config), indent=2), encoding="utf-8")
    logger.info("wrote %s", path)


def main() -> None:
    """Produce all results into results/."""
    logging.basicConfig(level=logging.INFO)
    OUT.mkdir(exist_ok=True)
    write_record(FigureConfig(name="example", seed=0, commit=commit_hash()))


if __name__ == "__main__":
    main()
