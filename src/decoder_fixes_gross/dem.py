"""Detector error model of the gross-code memory circuit at any physical error rate.

The circuit is the 12-round Z-memory syndrome-extraction circuit of the [[144,12,12]]
bivariate bicycle code generated by ``build_circuit`` of Gong, Cammerer and Renes [1]_ at
p = 1e-3, stored as package data; ``data/PROVENANCE.md`` records the call.

References
----------
.. [1] A. Gong, S. Cammerer and J. M. Renes, "Toward Low-latency Iterative Decoding of
   QLDPC Codes Under Circuit-Level Noise", arXiv:2403.18901 (2024).
"""

from dataclasses import dataclass
from functools import cache
from importlib.resources import files

import numpy as np
import scipy.sparse as sp
import stim
from numpy.typing import NDArray

# Every noise argument of the stored circuit equals this rate.
_P_STORED = 1e-3
# Largest argument Stim accepts for DEPOLARIZE1, the most restrictive channel in the circuit.
_P_MAX = 0.75

_ColumnKey = tuple[tuple[int, ...], tuple[int, ...]]


@dataclass(frozen=True, eq=False)
class Dem:
    """Detector error model as check matrices and priors.

    Attributes
    ----------
    h : scipy.sparse.csc_matrix
        Detector-by-column check matrix, uint8 with entries 0 and 1.
    l : scipy.sparse.csc_matrix
        Observable-by-column matrix, uint8 with entries 0 and 1, with as many columns as ``h``.
    priors : numpy.ndarray
        Probability of each column at ``p``, float64 of shape [n_columns].
    p : float
        Physical error rate the priors belong to.
    n_base : int
        Number of leading columns that are physical fault mechanisms; later columns, if any,
        were added by an augmentation.

    The arrays of ``h``, ``l`` and ``priors`` are made read-only in place, so a model cannot
    change after construction.

    Raises
    ------
    ValueError
        If ``h``, ``l`` and ``priors`` disagree on the number of columns, or ``n_base`` is not
        in [1, n_columns].
    """

    h: sp.csc_matrix
    l: sp.csc_matrix
    priors: NDArray[np.float64]
    p: float
    n_base: int

    def __post_init__(self) -> None:
        """Check that the parts agree on the number of columns, then freeze the arrays."""
        n_columns = self.h.shape[1]
        if self.l.shape[1] != n_columns or self.priors.shape != (n_columns,):
            raise ValueError(
                f"h, l and priors must have the same number of columns; got h {self.h.shape}, "
                f"l {self.l.shape}, priors {self.priors.shape}"
            )
        if not 1 <= self.n_base <= n_columns:
            raise ValueError(f"n_base must be in [1, {n_columns}], got {self.n_base}")
        for array in (*_arrays_of(self.h), *_arrays_of(self.l), self.priors):
            array.flags.writeable = False


def _arrays_of(matrix: sp.csc_matrix) -> tuple[NDArray[np.generic], ...]:
    return (matrix.data, matrix.indices, matrix.indptr)


def dem_at(p: float) -> Dem:
    """Return the detector error model of the stored circuit at physical error rate ``p``.

    The circuit at ``p`` is the stored circuit with every noise argument multiplied by
    p / 1e-3. Its Stim detector error model is flattened, and mechanisms with the same
    detectors and observables are merged into one column whose prior is the sum of their
    probabilities, as in ``dem_to_check_matrices`` of Gong, Cammerer and Renes; the exact
    combination of independent mechanisms differs from the sum at second order.
    Columns are in order of first appearance in the flattened model. They depend only on
    which mechanisms exist, so they are the same at every ``p``.

    Parameters
    ----------
    p : float
        Physical error rate, in (0, 3/4]; Stim rejects single-qubit depolarizing noise
        above 3/4.

    Returns
    -------
    Dem
        The model at ``p`` with 936 detectors, 12 observables and 8,784 columns, all of them
        physical (``n_base`` equals the number of columns).

    Raises
    ------
    ValueError
        If ``p`` is not in (0, 3/4].
    """
    if not 0 < p <= _P_MAX:
        raise ValueError(f"p must be in (0, {_P_MAX}], got {p}")
    keys, h, l = _columns()
    priors = np.zeros(h.shape[1])
    for key, probability in _mechanisms(_circuit_at(p).detector_error_model()):
        priors[keys[key]] += probability
    return Dem(h=h.copy(), l=l.copy(), priors=priors, p=p, n_base=h.shape[1])


def _stored_circuit() -> stim.Circuit:
    text = (files("decoder_fixes_gross") / "data" / "gross_z_r12.stim").read_text()
    return stim.Circuit(text)


def _circuit_at(p: float) -> stim.Circuit:
    return _scaled(_stored_circuit(), p / _P_STORED)


def _scaled(circuit: stim.Circuit, factor: float) -> stim.Circuit:
    """Return ``circuit`` with every noise argument multiplied by ``factor``.

    Precondition: every noise argument equals the stored rate. ``REPEAT`` blocks are kept,
    because the order of mechanisms in the model, and so the column order, depends on them.
    """
    out = stim.Circuit()
    for k in range(len(circuit)):
        item = circuit[k]
        if isinstance(item, stim.CircuitRepeatBlock):
            body = _scaled(item.body_copy(), factor)
            out.append(stim.CircuitRepeatBlock(item.repeat_count, body))
            continue
        assert isinstance(item, stim.CircuitInstruction)
        args = item.gate_args_copy()
        if stim.gate_data(item.name).is_noisy_gate:
            assert all(arg == _P_STORED for arg in args), (item.name, args)
            args = [arg * factor for arg in args]
        out.append(stim.CircuitInstruction(item.name, item.targets_copy(), args, tag=item.tag))
    return out


def _mechanisms(model: stim.DetectorErrorModel) -> list[tuple[_ColumnKey, float]]:
    """Return (sorted detectors, sorted observables) and probability of each error, in order."""
    flat = model.flattened()
    mechanisms = []
    for k in range(len(flat)):
        instruction = flat[k]
        assert isinstance(instruction, stim.DemInstruction)
        if instruction.type != "error":
            continue
        targets = [t for t in instruction.targets_copy() if isinstance(t, stim.DemTarget)]
        assert len(targets) == len(instruction.targets_copy())
        assert not any(t.is_separator() for t in targets)
        detectors = tuple(sorted(t.val for t in targets if t.is_relative_detector_id()))
        observables = tuple(sorted(t.val for t in targets if t.is_logical_observable_id()))
        mechanisms.append(((detectors, observables), instruction.args_copy()[0]))
    return mechanisms


@cache
def _columns() -> tuple[dict[_ColumnKey, int], sp.csc_matrix, sp.csc_matrix]:
    """Return the column index of each key and the matrices ``h`` and ``l``, from p = 1e-3."""
    model = _stored_circuit().detector_error_model()
    keys: dict[_ColumnKey, int] = {}
    for key, _ in _mechanisms(model):
        keys.setdefault(key, len(keys))
    detectors = [key[0] for key in keys]
    observables = [key[1] for key in keys]
    return (
        keys,
        _incidence(detectors, model.num_detectors),
        _incidence(observables, model.num_observables),
    )


def _incidence(supports: list[tuple[int, ...]], n_rows: int) -> sp.csc_matrix:
    """Return the 0/1 matrix whose column j has ones in the rows ``supports[j]``."""
    indptr = np.cumsum([0, *(len(s) for s in supports)])
    indices = np.fromiter((i for s in supports for i in s), dtype=np.int64, count=indptr[-1])
    data = np.ones(indptr[-1], dtype=np.uint8)
    return sp.csc_matrix((data, indices, indptr), shape=(n_rows, len(supports)))
